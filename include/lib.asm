  ;=============================================================================;
  ;  функция получает размер строки и возвращает это значение                   ;
  ;                                                                             ;
  ;  вход:         ds:si - адрес строки                                         ;
  ;                                                                             ;
  ;  выход:        cx - размер строки (в байтах)                                ;
  ;                                                                             ;
  ;  алгоритм:     циклом доходим до конца строки (до нулевого символа)         ;
  ;                                                                             ;
  ;  история:      31.12.2022 - дата создания                                   ;
  ;                                                                             ;
  ;  примечание:   1) нулевой символ в конце тоже считается в размер строки     ;
  ;                2) регистр si указывает на конец строки (на нулевой символ)  ;
  ;=============================================================================;
  getLenString:
