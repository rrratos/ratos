  hex2asciiWord:
         ; запоминаем регистр

         push    ax

         ; переводим старший байт

         and     ax, 0xFF00
         shr     ax, 8

         call    hex2asciiByte

         ; переносим его в старшие байты 32-битного регистра (2 старших байта)

         movzx   ebx, bx
         shl     ebx, 16

         ; восстанавливаем регистр

         pop     ax

         ; переводим младший байт

         and     ax, 0x00FF
         call    hex2asciiByte

         ret

