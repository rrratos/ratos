  ;=============================================================================;
  ;  функция сравнивает две строки до тех пор, покане будут найдены различные   ;
  ;  символы или не будет достигнут конец строки                                ;
  ;                                                                             ;
  ;  вход:         es:si - адрес проверяемой строки,                            ;
  ;                ds:di - адрес проверяющей строки,                            ;
  ;                                                                             ;
  ;                cx - размер проверяемой строки (в байтах)                    ;
  ;                                                                             ;
  ;  выход:        установлены результаты команды cmpsb, после проверки строк   ;
  ;                                                                             ;
  ;  алгоритм:     функция выходит в случаях:                                   ;
  ;                                1) если cx=0;                                ;
  ;                                2) если al=0;                                ;
  ;                                3) если zf=1.                                ;
  ;                                                                             ;
  ;  история:      31.12.2022 - дата создания                                   ;
  ;                                                                             ;
  ;  примечание:   нет                                                          ;
  ;=============================================================================;
  cmpStrings:
           ; запоминаем регистр

           push    bx
           push    cx
           push    dx

           .loop:
                    cmpsb       ; сравниваем символы из соответствующих строк
                    jne     .noDone     ; если не равны, то выходим c отрицательным результатом

                    dec      cx
                    jz       .done

                    jmp     .loop


           ; строки равны
           .done:
                   mov     ax, 0
                   jmp     .exit


           ; строки не равны
           .noDone:
                   mov     ax, 1


           ; выход
           .exit:
                   ; восстанавливаем регистр

                   pop     dx
                   pop     cx
                   pop     bx
                   ret


