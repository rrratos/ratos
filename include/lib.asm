  ;=============================================================================;
  ;  функция переводит из HEX-формата в ASCII-понятную цифру (байт)             ;
  ;                                                                             ;
  ;  вход:         al - число в HEX-формате                                     ;
  ;                                                                             ;
  ;  выход:        bx - число в ASCII-формате                                   ;
  ;                                                                             ;
  ;  алгоритм:     каждый полубайт числа нужно перевести в ASCII-формат с       ;
  ;                помощью функции hex2asciiHalfByte (см. алгоритм функции)     ;
  ;                                                                             ;
  ;  история:      31.12.2022 - дата создания                                   ;
  ;                                                                             ;
  ;  примечание:   нет                                                          ;
  ;=============================================================================;
  hex2asciiByte:
         ; запоминаем регистр

         mov     bx, ax

         ; переводим в ASCII-формат старший полубайт

         and     al, 0xF0                ; очищаем младший полубайт
         shr     al, 4                   ; перемещаем старший полубайт в младший полубайт

         call    hex2asciiHalfByte
         mov     bh, al                  ; сохраняем результат

         ; переводим в ASCII-формат младший полубайт

         mov     al, bl                  ; восстанавливаем регистр

         and     al, 0x0F                ; очищаем старший полубайт
         call    hex2asciiHalfByte

         mov     bl, al
         ret


