  ;=============================================================================;
  ;  функция переводит из HEX-формата в ASCII-понятную цифру (полубайт)         ;
  ;                                                                             ;
  ;  вход:         al - число в HEX-формате (старшие биты очищены)              ;
  ;                                                                             ;
  ;  выход:        al - число в ASCII-формате                                   ;
  ;                                                                             ;
  ;  алгоритм:     1) прибавляем к числу '0', чтобы превратить его в символ     ;
  ;                   ASCII                                                     ;
  ;                2) если символ ASCII больше '9', то прибавляем еще 7         ;
  ;                                                                             ;
  ;  история:      31.12.2022 - дата создания                                   ;
  ;                                                                             ;
  ;  примечание:   нет                                                          ;
  ;=============================================================================;
  hex2asciiHalfByte:
         add     al, '0'                 ; переводим в ASCII-формат

         cmp     al, '9'                 ; 16-ричное число больше '9'??
         jle     .exit                   ; если нет, то выходим без изменения

         add     al, 7                   ; теперь число будет больше '9'

         ; выход
         .exit:
         ret

