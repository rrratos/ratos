           ; запоминаем регистры

           push    es

           ; переводим из координат x, y в координаты относительно видеобуфера

           call    getXYcoordinate

           ; видеобуфер

           push    orgVideoBufferTextModeColour
           pop     es

           ; цикл
           .loop:
                   mov     al, [es:di]

                   cmp     al, 1
                   je      .doLoop

                   mov     [es:di+1], ah

                   dec     bx
                   jz      .exit

                   inc     di
                   inc     di
                   jmp     .loop

           .doLoop:
                   push    ax
                   push    ax
                   pop     dx

                   and     ah, 0xF0
                   and     dh, 0xF0

                   shr     dh, 4
                   or      ah, dh

                   mov     [es:di+1], ah

                   dec     bx
                   jz      .preExit

                   inc     di
                   inc     di

                   pop     ax
                   jmp     .loop

           .preExit:
                   pop     ax

           ; выход
           .exit:
                   ; восстанавливаем регистры

                   pop     es
                   ret


