  getXYcoordinate:
           ; переводим из координат x, y в координаты относительно видеобуфера

           ; алгоритм:
           ; (y * widthScreen + x) * 2,
           ;
           ; где x, y — координаты,
           ;     widthScreen — ширина экрана (в данном случае 80)

           ;  -----> запоминаем регистры

           push    ax
           push    bx
           push    dx

           ; -----> 1) y * widthScreen

           mov     di, 80
           movzx   ax, ch
           mul     di

           ; -----> 2) temp + x

           movzx   bx, cl
           add     ax, bx

           ; -----> 3) temp * 2

           shl     ax, 1

           ;  -----> проверка на чётность

           test    ax, 1
           jnz     .addOdd

           ; выход
           .exit:
                   ; передаем результат функции в di

                   mov     di, ax

                   ; восстанавливаем регистры

                   pop     dx
                   pop     bx
                   pop     ax
                   ret

           ; превращаем нечетное число в четное
