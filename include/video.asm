  ;  функция выводит на экран строки\массивы\символы, заканчивающиеся нулём     ;
  ;  функция поддерживает форматный вывод                                       ;
  ;                                                                             ;
  ;  вход:         cl — x-координата,                                           ;
  ;                ch — y-координата,                                           ;
  ;                                                                             ;
  ;                ds:si - адрес строки,                                        ;
  ;                ah - цвет и атрибуты (см. таблицу 1.3)                       ;
  ;                                                                             ;
  ;  выход:        bx - количество записанных символов                          ;
  ;                                                                             ;
  ;                di - координата относительно видеобуфера, указывающая конец  ;
  ;                строки                                                       ;
  ;                                                                             ;
  ;                cl — x-координата конца строки,                              ;
  ;                ch — y-координата конца строки                               ;
  ;                                                                             ;
  ;  алгоритм:     для записи символа в экран нужно знать организацию видеобу-  ;
  ;                фера определенного видеорежима. По умолчанию в RatOS ус-     ;
  ;                тановлен 3-ий видеорежим — videoTextMode80x25.               ;
  ;                                                                             ;
  ;                организация видеобуфера этого видеорежима показана в         ;
  ;                таблице 1.3.                                                 ;
  ;                                                                             ;
  ;                функция записывает в видеобуфер по четным адресам символ, по ;
  ;                нечетным — атрибуты символа.                                 ;
  ;                                                                             ;
  ;                функция поддерживает форматный вывод строки с помощью симво- ;
  ;                ла '/x', где 'x' параметр форматирования:                    ;
  ;                         \s - один символ,                                   ;
  ;                         \c - строка,                                        ;
  ;                         \d - десятичное число,                              ;
  ;                         \h - шестнатциричное число,                         ;
  ;                         \p - указатель,                                     ;
  ;                         \n - новая строка,                                  ;
  ;                         \b - 1-секундный писк,                              ;
  ;                         \r - вывод значений регистров (общего назначения,   ;
  ;                              флагов, сегментов и управления процессором),   ;
  ;                         \\ - вывод '\'
  ;                         \colors[c] - изменяет цвет символов и фона,
  ;                                                                             ;
  ;  история:      31.12.2022 - дата создания                                   ;
  ;                                                                             ;
  ;  примечание:   нет                                                          ;
  ;=============================================================================;
  print:
           ; запоминаем регистры

           push    es

           ; переводим из координат x, y в координаты относительно видеобуфера

           call    getXYcoordinate

           ; видеобуфер

           push    orgVideoBufferTextModeColour
           pop     es

           ; запоминаем указатель начала строки

           mov     [pointerString], si

           ; запоминаем x-координату

           mov     [.temp], cl

           ; вычисляем конец строки

           push    si                 ; запоминаем регистры
           push    cx                 ; ...

           call    getLenString       ; получаем размер строки

           mov     dx, cx             ; передаем в dx

           pop     cx                 ; восстанавливаем регистры
           pop     si                 ; ...

           ; очищаем количество записанных символов

           xor     bx, bx

           ; цикл
           .loop:
                   lodsb              ; считываем символ

                   cmp     al, ASCodeNull ; конец строки??
                   jz      .exit      ; если да, то выходим

                   cmp     al, '/'    ; форматирование??
                   jz      .format    ; если да, то форматируем текст

                   stosw              ; записываем символ с атрибутом в видеобуфер

                   inc     bx         ; следующий символ
                   call    addCoordX  ; увеличиваем X-координату

                   jmp     .loop      ; продолжаем цикл


           ; форматирование
           .format:
                   lodsb              ; загружаем параметр

                   push    ax
                   CHECK_azAZ_SHORT al, .format.register, .format.cont1

                .format.cont1:
                   pop     ax

                .format.cont2:
                   cmp     al, 'n'    ; новая строка??
                   je      .newLine

                   cmp     al, 's'    ; вывод символа??
                   je      .printB

                   cmp     al, 'x'    ; вывод HEX-числа??
                   je      .printHex

                   cmp     al, 'd'    ; вывод DEC-числа??
                   je      .printDec

                   cmp     al, 'c'    ; вывод строки??
                   je      .printString

                   jmp     .loop      ; продолжаем цикл

                .format.register:
                   pop     ax
                   and     al, 0xDF
                   jmp     .format.cont2

           ; форматирование - новая строка
           .newLine:
                   call    addCoordY       ; увеличиваем Y-координату
                   mov     cl, [.temp]     ; X-координата

                   call    getXYcoordinate ; переводим в координаты относительно видеопамяти
                   jmp     .loop           ; продолжаем цикл


           ; форматирование - вывод однобайтового символа
           .printB:
                   push    bx
                   push    ax



                   pop     ax
                   pop     bx

                   add     dx, 1
                   jmp     .loop           ; продолжаем цикл


           ; форматирование - вывод HEX-числа
           .printHex:
                   push    bx
                   push    si
                   push    ax



                   pop     ax
                   pop     si
                   pop     bx

                   add     dx, 2
                   jmp     .loop           ; продолжаем цикл


           ; форматирование - вывод DEC-числа
           .printDec:
                   push    bx
                   push    si
                   push    ax

                   mov     bx, [pointerString]
                   add     bx, dx

                   push    cx
                   HEX2DEC [bx], .buff
                   HEX2ASCII .buff, .array, 6
                   pop     cx
                   PRINTS .buff, 12, cx, white

                   pop     ax
                   pop     si
                   pop     bx

                   add     dx, 2
                   jmp     .loop           ; продолжаем цикл



           ; форматирование - вывод строки
           .printString:
                   push    bx
                   push    si
                   push    ax
                   push    cx

                   push    [pointerString]
                   push    dx

                   mov     bx, [pointerString]
                   add     bx, dx

                   mov     si, bx
                   call    print

                   pop     dx
                   add     dx, bx

                   pop     [pointerString]

                   pop     cx
                   pop     ax
                   pop     si
                   pop     bx
                   jmp     .loop

           ; выход
           .exit:
                   ; восстанавливаем регистры

                   pop     es
                   ret

 .temp db 0
 .buff rb 10
 .array rb 10
 .flags db 0

