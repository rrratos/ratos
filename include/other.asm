; Таблица 1.2 - формат команд OCWx контроллера PIC                           ;
;============================================================================;

  ;+++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
  ;+                             OCW1 команда                              +
  ;+-----------------------------------------------------------------------+
  ;+  Номер бита  |  Описание                                              +
  ;+--------------|--------------------------------------------------------+
  ;+  7-0         |  представляет значение IMR *, **                       +
  ;+--------------|--------------------------------------------------------+
  ;+  * - формат регистра IMR указан в табл. 1.3                           +
  ;+-----------------------------------------------------------------------+
  ;+  ** - чтобы получить текущее значение OCW1, нужно прочитать IMR       +
  ;+-----------------------------------------------------------------------+

  ;+++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
  ;+                           OCW2 команда (EOI)                          +
  ;+-----------------------------------------------------------------------+
  ;+  Номер бита  |  Описание                                              +
  ;+--------------|--------------------------------------------------------+
  ;+  7-5         |  комбинация команд (см. варианты команд в *) **        +
  ;+              |  7-ой бит - вариант вращения                           +
  ;+              |  6-ой бит - выбор                                      +
  ;+              |  5-ый бит - запрос окончания прерывания (EOI)          +
  ;+--------------|--------------------------------------------------------+
  ;+  4-3         |  зарезервировано                                       +
  ;+--------------|--------------------------------------------------------+
  ;+  2-0         |  уровень прерывания, на который должен реагировать     +
  ;+              |  контроллер                                            +
  ;+--------------|--------------------------------------------------------+
  ;+  * - команды:                                                         +
  ;+------------|---------|----------|-------------------------------------+
  ;+  Вращение  |  Выбор  |  Запрос  |  Описание                           +
  ;+------------|---------|----------|-------------------------------------+
  ;+  0         |   0     |    0     |  поворот в автоматическом режиме    +
  ;+            |         |          |  EOI (CLEAR)                        +
  ;+------------|---------|----------|-------------------------------------+
  ;+  0         |   1     |    0     |  неспецифическая команда EOI        +
  ;+------------|---------|----------|-------------------------------------+
  ;+  0         |   0     |    1     |  нет операции (NOP)                 +
  ;+------------|---------|----------|-------------------------------------+
  ;+  0         |   1     |    1     |  специфическая команда EOI          +
  ;+------------|---------|----------|-------------------------------------+
  ;+  1         |   0     |    0     |  поворот в автоматическом режиме    +
  ;+            |         |          |  EOI (SET)                          +
  ;+------------|---------|----------|-------------------------------------+
  ;+  1         |   0     |    1     |  поворот на неспецифический EOI     +
  ;+------------|---------|----------|-------------------------------------+
  ;+  1         |   1     |    0     |  установить приоритетную команду    +
  ;+------------|---------|----------|-------------------------------------+
  ;+  1         |   1     |    1     |  поворот на определенный EOI        +
  ;+------------|---------|----------|-------------------------------------+
  ;+  ** - команды нужны для успешного завершения IRQ и не только          +
  ;+-----------------------------------------------------------------------+


