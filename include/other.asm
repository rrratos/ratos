  ;=============================================================================;
  ;  функция изменяет адрес обработчика прерывания в определенном векторе       ;
  ;                                                                             ;
  ;  вход:         es:ax - адрес обработчика прерывания,                        ;
  ;                bx - номер вектора прерывания                                ;
  ;                                                                             ;
  ;  выход:        нет                                                          ;
  ;                                                                             ;
  ;  алгоритм:     в начале ОЗУ находится таблица векторов прерываний (IVT).    ;
  ;                Здесь от 0:0 по 0:0x400 хранится адрес обработчиков          ;
  ;                прерываний для каждого прерывания                            ;
  ;                                                                             ;
  ;  история:      01.01.2023 - дата создания                                   ;
  ;                                                                             ;
  ;  примечание:   работает только в реальном режиме                            ;
  ;=============================================================================;
  setHandlerInterrupt:
           ; запоминаем регистры

           push    bx
           push    ax

           ; блокируем внешние прерывания

           cli

           ; получаем адрес вектора прерывания в IVT

           mov     ax, 4           ; умножаем на 4, так как для описания адреса требуется 4 байта
                                   ; (сегмент и смещение)
           mul     bx
           mov     bx, ax          ; перемещаем адрес в bx

           ; восстанавливаем регистр

           pop     ax

           ; пишем в IVT адрес обработчика прерывания

           push    0               ; IVT находится в нулевом сегменте (в начале ОЗУ)
           pop     ds

           mov     [ds:bx], ax     ; пишем смещение
           mov     [ds:bx+2], es   ; пишем сегмент

           ; разблокируем внешние прерывания

           sti

           ; восстанавливаем регистр

           pop     bx
           ret


