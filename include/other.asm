; Таблица 1.1 - формат команд ICWx контроллера PIC                           ;
;============================================================================;

  ;+++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
  ;+                             ICW1 команда                              +
  ;+-----------------------------------------------------------------------+
  ;+  Номер бита  |  Описание                                              +
  ;+--------------|--------------------------------------------------------+
  ;+  7-4         |  Эти биты должны быть равны 0001b *                    +
  ;+--------------|--------------------------------------------------------+
  ;+  3           |  (1) работа в режиме срабатывания триггера уровня      +
  ;+              |  (0) работа в режиме срабатывания  по фронту           +
  ;+--------------|--------------------------------------------------------+
  ;+  2           |  (1) интервал адресов CALL равен 4                     +
  ;+              |  (0) интервал адресов CALL равен 8 (обычно в X86)      +
  ;+--------------|--------------------------------------------------------+
  ;+  1           |  (1) только один PIC в системе                         +
  ;+              |  (0) PIC каскадируется с ведомыми PIC, и ICW3 должен   +
  ;+              |      быть отправлен на контроллер                      +
  ;+--------------|--------------------------------------------------------+
  ;+  0           |  (1) PIC ожидает получить ICW4 во время инициализации  +
  ;+              |  (0) PIC не ожидает получить ICW4 во время             +
  ;+              |      инициализации                                     +
  ;+--------------|--------------------------------------------------------+
  ;+  * - 4-ый бит означает инициализация контроллера PIC, биты 7-5        +
  ;+      предназначены не для архитектуре X86 процессоров                 +
  ;+-----------------------------------------------------------------------+

  ;+++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
  ;+                             ICW2 команда                              +
  ;+-----------------------------------------------------------------------+
  ;+  Номер бита  |  Описание                                              +
  ;+--------------|--------------------------------------------------------+
  ;+  7-0         |  указывает на вектора прерываний IRQ *                 +
  ;+--------------|--------------------------------------------------------+
  ;+  * - это предназначено только для процессоров с архитектурой X86      +
  ;+-----------------------------------------------------------------------+

  ;+++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
  ;+                             ICW3 команда                              +
  ;+-----------------------------------------------------------------------+
  ;+                        Для ведущего контроллера                       +
  ;+-----------------------------------------------------------------------+
  ;+  Номер бита  |  Описание                                              +
  ;+--------------|--------------------------------------------------------+
  ;+  7-0         |  указывает, какой IRQ подключен к подчинненому         +
  ;*              |  контроллеру PIC                                       +
  ;+--------------|--------------------------------------------------------+
  ;+--------------|--------------------------------------------------------+
  ;+                      Для подчиненного контроллера                     +
  ;+-----------------------------------------------------------------------+
  ;+  Номер бита  |  Описание                                              +
  ;+--------------|--------------------------------------------------------+
  ;+  7-3         |  зарезервировано                                       +
  ;+--------------|--------------------------------------------------------+
  ;+  2-0         |  номер IRQ, к которому ведущий PIC подключается *      +
  ;+--------------|--------------------------------------------------------+
  ;+  * - в двоичном представлении                                         +
  ;+-----------------------------------------------------------------------+

  ;+++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
  ;+                             ICW4 команда                              +
  ;+-----------------------------------------------------------------------+
  ;+  Номер бита  |  Описание                                              +
  ;+--------------|--------------------------------------------------------+
  ;+  7-5         |  зарезервировано                                       +
  ;+--------------|--------------------------------------------------------+
  ;+  4           |  специальный полностью вложенный режим. Используется в +
  ;+              |  системах с большим количеством каскадных контроллеров +
  ;+--------------|--------------------------------------------------------+
  ;+  3           |  (1) контроллер работает в буферном режиме             +
  ;+--------------|--------------------------------------------------------+
  ;+  2           |  (1) выбирает мастер буфера. Очищается, если буфер     +
  ;+              |      подчиненный *                                     +
  ;+--------------|--------------------------------------------------------+
  ;+  1           |  (1) по последнему импульсу подтверждения прерывания   +
  ;+              |      контроллер автоматически выполняет операцию       +
  ;+              |      окончания прерывания (EOI)                        +
  ;+--------------|--------------------------------------------------------+
  ;+  0           |  (1) контроллер работает в режиме X86                  +
  ;+              |  (0) контроллер работает в режиме MCS-80/86            +
  ;+--------------|--------------------------------------------------------+
  ;+  * - использовать, если 3-ий бит установлен (если контроллер работает +
  ;+      в буферном режиме)                                               +
  ;+-----------------------------------------------------------------------+


