  ;=============================================================================;
  ;  функция инициализирует PIC с программными значениями                       ;
  ;                                                                             ;
  ;  вход:         [bp+4] - ICW1 (формат записи приведен в табл. 1.1), *        ;
  ;                [bp+6] - ICW2 (формат записи приведен в табл. 1.1), * **     ;
  ;                [bp+8] - ICW3 (формат записи приведен в табл. 1.1), * ***    ;
  ;                [bp+10] - ICW4 (формат записи приведен в табл. 1.1), *       ;
  ;                                                                             ;
  ;  выход:        нет                                                          ;
  ;                                                                             ;
  ;  алгоритм:     функция инициализирует регистры контроллера последовательно, ;
  ;                от ICW1 до ICW4 (команды для инициализации PIC). Функция     ;
  ;                также в начале отключает внешние прерывания, для корректной  ;
  ;                работы ОС                                                    ;
  ;                                                                             ;
  ;  история:      01.01.2023 - дата создания                                   ;
  ;                                                                             ;
  ;  примечание:   1) все ICWx предоставлены для обоих контроллеров (ведущего   ;
  ;                   и подчиненного)                                           ;
  ;                2) номер вектора должен быть кратным 8                       ;
  ;                3) биты от 2-3 должны быть равны 11b                         ;
  ;=============================================================================;
  initPIC:
           ; запоминаем регистры

           push    bp
           push    ax

           ; блокируем внешние прерывания

           cli

           ; инициализация регистра ICW1

           mov     al, cl                    ; получаем значение из регистра

           out     IOportPIC1RegCommand, al  ; для ведущего контроллера
           out     IOportPIC2RegCommand, al  ; для подчинненого контроллера

           ; инициализация регистра ICW2

           mov     al, ch

           out     IOportPIC1InitController, al

           add     al, 8                         ; вектора IRQ подчинненого контроллера идут сразу после вектор ведущего
           out     IOportPIC2InitController, al

           ; инициализация регистра ICW3

           mov     ax, dx

           out     IOportPIC1InitController, al

           mov     al, ah
           out     IOportPIC2InitController, al

           ; инициализация регистра ICW4

           mov     al, bl

           out     IOportPIC1InitController, al

           and     al, 11111011b                 ; очищаем бит для включения подчиненного контроллера
           out     IOportPIC2InitController, al

           ; восстанавливаем внешние прерывания

           sti

           ; восстанавливаем регистры

           pop     ax
           pop     bp

           ret

  ; определения функции

  ParamStackICW1  equ [bp+4]    ; адрес 1-ого параметра
  ParamStackICW2  equ [bp+6]    ; адрес 2-ого параметра
  ParamStackICW3  equ [bp+8]    ; адрес 3-ого параметра
  ParamStackICW4  equ [bp+10]   ; адрес 4-ого параметра


