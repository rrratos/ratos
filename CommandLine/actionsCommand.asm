  ;+  (color)     |  (color) = 0, черный
  ;+--------------|--------------------------------------------------------+
  ;+  TEST (x)    |  команда предназначена для внутреннего использования   +
  ;+              |  RatOS,                                                +
  ;+              |  (x) = 0, изменяет глобальный цвет окна в зеленый      +
