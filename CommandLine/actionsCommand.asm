  ;=============================================================================;
  ;  функция возвращает код команды                                             ;
  ;                                                                             ;
  ;  вход:         нет                                                          ;
  ;                                                                             ;
  ;  выход:        al - код команды (см. табл. 1.1)                             ;
  ;                                                                             ;
  ;  алгоритм:     функция читает буфер клавиатуры и определяет команду         ;
  ;                                                                             ;
  ;  история:      01.01.2023 - дата создания                                   ;
  ;                                                                             ;
  ;  примечание:   нет                                                          ;
