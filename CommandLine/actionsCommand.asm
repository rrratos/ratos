  getCommandKey:
           ; запоминаем регистры

           push    cx
           push    dx
           push    di
           push    si

           ; буфер пуст??

           cmp     [lastSymbolBuffer], 0
           je      .notEnteredCommand

           ; адреса

           mov     di, strCommand
           mov     si, bufferKeyboard

           ; подготовка регистров

           xor     cx, cx
           ;mov     bx, 7

           .preLoop:
                   mov     cl, [di]
                   mov     dl, [di+1]

                   add     di, 2
                   mov     [.temp], cx

           ; цикл
           .loop:
                   mov     al, [si]

                   cmp     al, ' '
                   jz      .check

                   push    ax
                   CHECK_azAZ_SHORT al, .cont2, .register

                .cont2:
                   pop     ax

                .cont3:
                   cmpsb       ; сравниваем символы из соответствующих строк
                   jne     .noDone     ; если не равны, то выходим c отрицательным результатом

                   dec      cx
                   jz       .getCode

                   jmp     .loop

           .register:
                   pop     ax

                   and     al, 0xDF
                   mov     [si], al
                   jmp     .cont3

            .temp  dw 0

            .check:
                   mov     al, [di]

                   cmp     al, 0
                   je      .getCode

            .noDone:
                   ;dec     bx
                   ;jz      .unknownCommand

                   add     di, [.temp]
                   dec     di

                   cmp     word [di], 0xFFFF
                   je      .unknownCommand

                   ;cmp     ax, 0
                   ;je      .getCode

                   mov     si, bufferKeyboard
                   jmp     .preLoop

           ; получить код команды
           .getCode:
                   mov     al, dl                 ; передаем код команды
                   jmp     .exit                  ; выходим

           ; команда не введена
           .notEnteredCommand:
                   mov     al, 0xFE
                   jmp     .exit


           ; неизвестная команда
           .unknownCommand:
                   mov     al, 0xFF               ; код неизвестной команды


           ; выход
           .exit:
                   ; восстанавливаем регистры

                   pop     si
                   pop     di
                   pop     dx
                   pop     cx
                   ret


